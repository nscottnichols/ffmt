#!/usr/bin/env python3
"""Generate manuscript tables and an explicit selection ledger from measured JSON."""
import argparse
from collections import Counter
import hashlib
import json
from pathlib import Path


def tex(value):
    replacements = {"\\": r"\textbackslash{}", "_": r"\_", "%": r"\%",
                    "&": r"\&", "#": r"\#", "$": r"\$", "{": r"\{",
                    "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}
    return "".join(replacements.get(c, c) for c in str(value))


def table(header, rows, layout, long=False):
    environment = "longtable" if long else "tabular"
    lines = [r"\begin{" + environment + "}{" + layout + "}", r"\toprule",
             " & ".join(header) + r" \\", r"\midrule"]
    if long:
        lines += [r"\endhead"]
    return "\n".join(lines + [" & ".join(tex(cell) for cell in row) + r" \\" for row in rows] +
                     [r"\bottomrule", r"\end{" + environment + "}"])


def system(profile, device=""):
    if "A40" in device:
        return "A40"
    if "GH200" in device:
        return "GH200"
    if "Max" in device:
        return "Intel Max"
    # The profile is a resource selector, not a claim of device identity.
    return {"rome": "Rome", "gh200": "Arm/GH200", "mi300x": "MI300X", "h100": "h100 profile",
            "chiatta": "Intel Max"}.get(profile, profile)


def fingerprint(run):
    return (run.get("source_fingerprint_sha256") or hashlib.sha256(
        json.dumps(run.get("source_files"), sort_keys=True, separators=(",", ":")).encode()).hexdigest())[:8]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--qualification", required=True, type=Path)
    parser.add_argument("--benchmarks", required=True, type=Path)
    parser.add_argument("--coverage", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument("--selection-output", type=Path)
    args = parser.parse_args()
    qualification = json.loads(args.qualification.read_text())
    benchmarks = json.loads(args.benchmarks.read_text())
    coverage = json.loads(args.coverage.read_text())
    output = ["% Generated by tools/paper_tables.py; edit the evidence or generator."]
    rows = []
    for run in qualification["runs"]:
        for config in run["configurations"]:
            counts = config["positive_counts"]
            memory = config.get("numeric_memory") or {}
            inventory = " ".join(x["name"] for x in run.get("hardware", {}).get("discovered_accelerators", []))
            rows.append([system(run["profile"], (config.get("device") or "") + " " + inventory), config["route"],
                "O" + str(config["optimization"]),
                (run["source"].get("commit") or "unknown")[:8] + ("+W" if run["source"].get("worktree") else ""),
                str(counts.get("pass", 0)) + "/" + str(config["unique_logical_cases"]),
                str(memory.get("passed", "--")) + "/" + str(memory.get("input_cases", "--"))
                if memory.get("status") in ("pass", "mismatch") else memory.get("status", "not run")])
    output += [r"\newcommand{\qualificationtable}{%", r"{\small",
        table(["System", "Route", "Opt.", "Source", "Exact/stdout", "Exact/numeric"], rows, "llllrr", long=True), "}}"]
    # Keep one canonical group per key, choosing the latest captured run. Every
    # row's exact input manifest and header fingerprint goes into the ledger.
    # Historical runs remain in the full evidence and are not relabeled current.
    selected = {}
    for run in sorted(benchmarks["runs"], key=lambda x: (x.get("started") or "", x["raw_manifest"])):
        for row in run["results"]:
            if row["status"] != "measured" or row["capacity"] != 128 or row["multi_tu"] or row["calls"] != 1:
                continue
            presentation = row.get("presentation", "explicit_e8" if row["family"] == "float" else "integer_d")
            key = (run["profile"], row["route"], row["engine"], row["family"], row["mode"], presentation)
            selected[key] = (run, row)
    rows, ledger = [], []
    for key, (run, row) in sorted(selected.items()):
        device = str(row.get("actual_device") or run.get("actual_devices") or "")
        data = "float {}" if key[-1] == "shortest" else "float .8e" if row["family"] == "float" else "integer"
        rows.append([system(run["profile"], device), row["route"], row["engine"], data, row["mode"],
                     fingerprint(run), "%.2f" % row["metrics"]["median_ns_per_call"]])
        ledger.append(dict(key=list(key), raw_manifest=run["raw_manifest"],
                           raw_manifest_sha256=run["raw_manifest_sha256"],
                           headers_fingerprint=fingerprint(run), revision=run.get("revision"),
                           actual_devices=run.get("actual_devices"), source_files=run.get("source_files")))
    output += [r"\newcommand{\benchmarktable}{%", r"{\scriptsize",
        table(["System", "Route", "Engine", "Data", "Sink", "Headers", "ns/call"], rows, "llllllr", long=True), "}}"]
    rows = [["Regions", coverage["covered"], coverage["count"], "%.2f" % coverage["percent"]]]
    for label, key in [("Executable lines", "lines"), ("Branch edges", "branches")]:
        item = coverage[key]
        rows.append([label, item["covered"], item["count"], "%.2f" % item["percent"] if item["percent"] is not None else "--"])
    output += [r"\newcommand{\coveragetable}{%", table(["Metric", "Covered", "Instrumented", "Percent"], rows, "lrrr"), "}"]
    # Focused shortest-conversion probes expose staging and call-count effects.
    rows = []
    for run in benchmarks["runs"]:
        for row in run.get("resource_probes", []):
            if row.get("presentation") != "shortest" or row["status"] != "compiled":
                continue
            gpu_frame = row.get("gpu_stack_frame_bytes") or row.get("gpu_scratch_bytes_per_lane") or ["--"]
            registers = row.get("gpu_registers") or row.get("gpu_vgprs") or ["--"]
            command = row.get("compile", {}).get("command", [])
            target = ",".join(row.get("target_architectures", [])) or next((x.split("=", 1)[1] for x in command
                if x.startswith(("-arch=", "--offload-arch="))), "unspecified")
            rows.append([target, row["route"],
                         row["capacity"], row["mode"], row["calls"],
                         ",".join(map(str, registers)), ",".join(map(str, gpu_frame))])
    output += [r"\newcommand{\resourcetable}{%", r"{\small",
        table(["GPU target", "Route", "Stage", "Sink", "Calls", "Regs/VGPR", "Frame/scratch B"], rows, "llrlrrr", long=True), "}}"]
    counts = Counter(row["status"] for run in benchmarks["runs"] for row in run["results"])
    output += [r"\newcommand{\measuredgroups}{" + str(counts["measured"]) + "}"]
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(output) + "\n")
    if args.selection_output:
        args.selection_output.parent.mkdir(parents=True, exist_ok=True)
        args.selection_output.write_text(json.dumps(dict(policy="Latest captured measured run per profile/route/engine/family/sink/presentation; one call, capacity 128, single TU", rows=ledger), indent=2) + "\n")


if __name__ == "__main__":
    main()
