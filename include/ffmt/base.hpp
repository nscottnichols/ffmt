FMT_HD auto printf_to(OutputIt out, runtime_format_string<Char> pattern,
                      const Args &...args) -> format_to_result<OutputIt> {
  return printf_to_n(out, (std::numeric_limits<std::size_t>::max)(), pattern,
                     args...);
}
